#!/usr/bin/env python3
"""Write the open-loop AC record for the inn-AC-grounded bench (issue #241).

  summarize_klt.py <record-id> <corners-dir> <superseded.csv> <out.csv> <out.md>

<corners-dir> holds what run_klt_record.sh kept: measurement.json (the
`klt pex --measure-command` document) and the two `klt sim` envelopes
{ac,op}.envelope.json (environment.remote names the batch job).
<superseded.csv> is the floating-inn record this one supersedes; it is only
read, to report the per-row shift.

Grades each row against the ratified bounds (spec/target-spec.md Sec 2, all
DR-2 worst-case into CL = 2 pF [DR-1]) and lists every failing corner. A miss
is a result and is reported; the exit status stays 0. Loud on a missing or
malformed input (exit 1, nothing written).
"""
from __future__ import annotations

import csv
import json
import sys
from pathlib import Path

BOUNDS = {  # row: (op, limit, unit)
    "av0_db": (">=", 37.8, "dB"),
    "gbw_hz": (">=", 4.74e6, "Hz"),
    "pm_deg": (">=", 60.0, "deg"),
    "iq_a": ("<=", 119.7e-6, "A"),
}
ROWS = tuple(BOUNDS)


def point_id(corner_id: str) -> tuple[str, str]:
    """mos_tt/1.20V/27C -> (mos_tt, mos_tt_27C_1.20V)."""
    proc, vdd, temp = corner_id.split("/")
    return proc, f"{proc}_{temp}_{vdd}"


def old_key(row: dict) -> str:
    t = int(float(row["temp_c"]))
    return f"{row['corner']}_{t}C_{float(row['vdd_v']):.2f}V"


def main(rid, cdir, old_csv, out_csv, out_md):
    cdir = Path(cdir)
    doc = json.load(open(cdir / "measurement.json"))
    pts = {}
    for c in doc["corners"]:
        proc, pid = point_id(c["corner_id"])
        v = {m["name"]: m["value"] for m in c["measurements"]}
        if set(v) != set(ROWS):
            sys.exit(f"summarize_klt: {c['corner_id']}: rows {sorted(v)}")
        pts[pid] = (proc, c["corner_id"], v)
    if len(pts) != 45:
        sys.exit(f"summarize_klt: {len(pts)} corners, expected 45")
    old = {old_key(r): r for r in csv.DictReader(open(old_csv))}
    jobs = []
    for kind in ("ac", "op"):
        env = json.load(open(cdir / f"{kind}.envelope.json"))
        r = (env.get("environment") or {}).get("remote") or {}
        if not r.get("job_id"):
            sys.exit(f"summarize_klt: {kind}.envelope.json has no environment.remote.job_id (not a batch run)")
        jobs.append((kind, r["job_id"], r.get("state")))

    with open(out_csv, "w", newline="") as f:
        w = csv.writer(f)
        w.writerow(["point_id", "corner", "temp_c", "vdd_v", "av0_db", "gbw_hz", "pm_deg", "iq_a"])
        for pid in sorted(pts):
            proc, cid, v = pts[pid]
            _, vdd, temp = cid.split("/")
            w.writerow([pid, proc, int(temp[:-1]), vdd[:-1],
                        *(f"{v[r]:.6g}" for r in ROWS)])

    lines = [f"# open-loop-ac record {rid} (inn AC-grounded)", "",
             "Generated by `sim/open-loop-ac/run_klt_record.sh` (issue #241) against "
             f"`design/netlist/opamp_core.spice` (snapshot: `netlist-snapshots/{rid}/opamp_core.spice`) "
             "through `klt sim` on the batch fleet, with the bench's `Cinn_acgnd inn vss 1` "
             "(1 F AC ground on `inn`) next to `Lbreak = 1e18 H`. Grid: cornerMOSlv.lib "
             "`mos_tt/ss/ff/sf/fs` [DR-1] x `{-40, 27, 125} C` x `{1.08, 1.20, 1.32} V` = 45 points, "
             "into `CL = 2e-12 F` [DR-1].", "",
             "Batch jobs: " + ", ".join(f"{k} `{j}` ({s})" for k, j, s in jobs) + ".", "",
             f"**Supersedes** (does not edit) `records/{Path(old_csv).stem}.*`, which measured with "
             "`inn` AC-floating (`Lbreak` only). Do not cite that record's GBW or PM.", "",
             "## Rows against the ratified bounds (45 corners)", "",
             "| row | bound | worst | at corner | corners failing | verdict |", "|---|---|---|---|---|---|"]
    for r, (op, lim, unit) in BOUNDS.items():
        vals = sorted((pts[p][2][r], p) for p in pts)
        worst = vals[0] if op == ">=" else vals[-1]
        bad = [p for v, p in vals if (v < lim if op == ">=" else v > lim)]
        lines.append(f"| {r} | {op} {lim:g} {unit} | {worst[0]:.6g} | {worst[1]} | {len(bad)} of 45 | "
                     f"{'PASS' if not bad else 'FAIL'} |")
    for r, (op, lim, unit) in BOUNDS.items():
        bad = [p for p in sorted(pts) if (pts[p][2][r] < lim if op == ">=" else pts[p][2][r] > lim)]
        if bad:
            lines += ["", f"Failing corners for `{r}`: " + ", ".join(f"{p} ({pts[p][2][r]:.6g})" for p in bad)]
    lines += ["", "## Shift against the superseded floating-inn record", "",
              "| row | min change | max change | unit |", "|---|---|---|---|"]
    for r, scale, unit in (("av0_db", 1, "dB"), ("gbw_hz", 1e-6, "MHz"), ("pm_deg", 1, "deg"), ("iq_a", 1e6, "uA")):
        col = {"av0_db": "av0_db", "gbw_hz": "gbw_hz", "pm_deg": "pm_deg", "iq_a": "ivdd_total_a"}[r]
        d = [(pts[p][2][r] - float(old[p][col])) * scale for p in pts]
        lines.append(f"| {r} | {min(d):+.4g} | {max(d):+.4g} | {unit} |")
    lines += ["", f"Per-point data: `records/{rid}.csv`. Raw envelopes and requests: `corners/{rid}/`.", ""]
    Path(out_md).write_text("\n".join(lines))


if __name__ == "__main__":
    if len(sys.argv) != 6:
        sys.exit(__doc__)
    main(*sys.argv[1:])
